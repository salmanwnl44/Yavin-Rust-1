/**
 * The author-facing type definitions (WS21, Developer Ecosystem): extension authors write a
 * `yavin-extension.json` manifest and an `extension.js` whose `activate(context, yavin)` is
 * called in the QuickJS host. `api.ts` is the single source of that contract; this module
 * derives the distributable ambient declaration (`extensions/yavin.d.ts`) from it so authors can
 * type-check their extensions (`import type { YavinApi } from "yavin"`) with editor autocomplete.
 *
 * The derivation is mechanical and pure so one function is the single source of truth: the
 * committed `yavin.d.ts` is generated by it, and `authoring.test.ts` regenerates and compares,
 * failing the moment `api.ts` changes without the typings being refreshed. This adds no runtime,
 * no API surface, and no capability -- it only describes what already exists, so it cannot widen
 * the sandbox.
 */

/** The module name authors import the API types from. */
export const AUTHOR_MODULE = "yavin";

/** Where the authored `.d.ts` is written, relative to the repository root. */
export const AUTHOR_TYPINGS_PATH = "extensions/yavin.d.ts";

/** The first line of the public contract in `api.ts` (everything from here on is the contract). */
const CONTRACT_MARKER = "export interface Disposable";

/**
 * The body of `api.ts`'s public contract: every exported declaration, verbatim, from the first
 * one to the end of the file (api.ts has no imports and no runtime code, so its tail is purely
 * the author-facing types). Throws if the contract marker is missing, so a refactor of api.ts
 * that moves the first declaration is caught rather than silently producing empty typings.
 */
export function contractBody(apiSource: string): string {
  const start = apiSource.indexOf(CONTRACT_MARKER);
  if (start < 0) throw new Error(`api.ts no longer starts its contract with "${CONTRACT_MARKER}".`);
  return apiSource.slice(start).replace(/\s+$/, "");
}

/**
 * The full `extensions/yavin.d.ts`: a header naming the API version and how to use it, then the
 * contract wrapped in `declare module "yavin"`. Byte-for-byte deterministic for a given api.ts
 * and version, which is what makes the drift-guard test exact.
 */
export function authorTypings(apiSource: string, apiVersion: string): string {
  return [
    `// Yavin Extension API ${apiVersion} -- type definitions for extension authors.`,
    `//`,
    `// AUTO-DERIVED from src/services/extensions/api.ts by authoringTypings.ts.`,
    `// Do not edit by hand: authoring.test.ts regenerates this and fails on drift.`,
    `//`,
    `// JavaScript (JSDoc):`,
    `//   /** @type {import("${AUTHOR_MODULE}").ExtensionModule} */`,
    `//   module.exports = { activate(context, yavin) { /* ... */ } };`,
    `// TypeScript:`,
    `//   import type { ExtensionContext, YavinApi } from "${AUTHOR_MODULE}";`,
    ``,
    `declare module "${AUTHOR_MODULE}" {`,
    contractBody(apiSource),
    `}`,
    ``,
  ].join("\n");
}
